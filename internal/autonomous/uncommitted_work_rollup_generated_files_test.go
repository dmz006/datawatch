// writeRollupGeneratedDocs writes the gate report, parity draft and registry
// row the daemon generates at finish time — really, with their hash sidecars
// — for the rig's Automaton, exactly as the daemon's own write does, and
// returns their three tracked paths relative to the project root. It does not
// touch the fake worktree.
func writeRollupGeneratedDocs(t *testing.T, r *uncommittedRollupRig) []string {
	t.Helper()
	rec := &changerecord.ChangeRecord{AutomatonID: r.prd.ID}
	opts := genartifacts.Options{Root: r.prd.ProjectDir}
	var rels []string
	for _, k := range []genartifacts.Kind{genartifacts.GateReport, genartifacts.ParityDraft, genartifacts.RegistryRow} {
		rel := genartifacts.TrackedPath(k, rec, opts)
		res, err := genartifacts.Write(k, "Generated by the daemon for this run.", rel, opts)
		if err != nil {
			t.Fatalf("write %s: %v", k, err)
		}
		if res.Status != genartifacts.Written {
			t.Fatalf("write %s = %s (%s); want written", k, res.Status, res.Reason)
		}
		rels = append(rels, rel)
	}
	return rels
}

// markUntrackedGenerated marks the rig's fake worktree with the three
// generated documents and their three sidecars, untracked ('??'), the way
// `git status` reports files the daemon has not staged.
func markUntrackedGenerated(t *testing.T, r *uncommittedRollupRig, rels []string) {
	t.Helper()
	dirty := map[string]string{}
	for _, rel := range rels {
		dirty[rel] = "??"
		dirty[genartifacts.SidecarRelPath(rel)] = "??"
	}
	r.git.mu.Lock()
	r.git.dirty = dirty
	r.git.mu.Unlock()
}

// The three documents the daemon generated at finish time sit untracked in
// the worktree the roll-up reads: none of them, nor any of their hash
// sidecars, may hold the Automaton.
func TestUncommittedRollupGeneratedFilesIgnoredCompletes(t *testing.T) {
	r := newUncommittedRollupRig(t, config.UncommittedWorkPolicyHold, nil)
	markUntrackedGenerated(t, r, writeRollupGeneratedDocs(t, r))

	got := r.run(t)
	if got.Status != PRDCompleted {
		t.Fatalf("status = %s; want completed (hold: %+v)", got.Status, got.UncommittedWork)
	}
	if got.UncommittedWork != nil {
		t.Errorf("the daemon's own documents raised a hold: %+v", got.UncommittedWork)
	}
	if qs := r.store.List(QuestionFilter{}); len(qs) != 0 {
		t.Errorf("the daemon's own documents raised a question: %+v", qs)
	}
}

// The same worktree with one real stray file on top: the Automaton holds,
// names exactly that file, and the question never lists a generated document
// or one of its sidecars.
func TestUncommittedRollupGeneratedFilesIgnoredStrayStillHolds(t *testing.T) {
	r := newUncommittedRollupRig(t, config.UncommittedWorkPolicyHold, nil)
	rels := writeRollupGeneratedDocs(t, r)
	markUntrackedGenerated(t, r, rels)

	const stray = "notes/stray.txt"
	if err := os.MkdirAll(filepath.Join(r.prd.ProjectDir, "notes"), 0o700); err != nil { // #nosec G301 -- test fixture
		t.Fatalf("make notes dir: %v", err)
	}
	if err := os.WriteFile(filepath.Join(r.prd.ProjectDir, filepath.FromSlash(stray)), []byte("operator note\n"), 0o644); err != nil { // #nosec G306 -- test fixture
		t.Fatalf("write stray file: %v", err)
	}
	r.git.mu.Lock()
	r.git.dirty[stray] = "??"
	r.git.mu.Unlock()

	got := r.run(t)
	if got.Status != PRDBlocked {
		t.Fatalf("status = %s; want blocked (hold: %+v)", got.Status, got.UncommittedWork)
	}
	if got.UncommittedWork == nil || len(got.UncommittedWork.Files) != 1 || got.UncommittedWork.Files[0] != stray {
		t.Fatalf("hold record = %+v; want exactly [%s]", got.UncommittedWork, stray)
	}

	qs := r.store.List(QuestionFilter{})
	if len(qs) != 1 {
		t.Fatalf("questions = %d; want 1", len(qs))
	}
	if !strings.Contains(qs[0].Text, stray) {
		t.Errorf("question lacks %q:\n%s", stray, qs[0].Text)
	}
	for _, rel := range rels {
		if strings.Contains(qs[0].Text, rel) {
			t.Errorf("question lists a generated document %q:\n%s", rel, qs[0].Text)
		}
		sidecar := genartifacts.SidecarRelPath(rel)
		if strings.Contains(qs[0].Text, sidecar) {
			t.Errorf("question lists a generated sidecar %q:\n%s", sidecar, qs[0].Text)
		}
	}
}
