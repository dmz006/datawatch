package autonomous

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/dmz006/datawatch/internal/config"
)

// TestDecomposeLintUnexecutableVerificationScript asserts the built-in
// warn rule: a command string or a missing script file is a finding on
// that task, a runnable script (or one the task creates) is not, the rule
// is in the default pack as a warning, and the built-in template pack
// raises no block finding.
func TestDecomposeLintUnexecutableVerificationScript(t *testing.T) {
	var rule Rule
	for _, r := range DefaultDecomposeLintRules() {
		if r.ID == "unexecutable_verification_script" {
			rule = r
		}
	}
	if rule.ID == "" {
		t.Fatal("unexecutable_verification_script missing from DefaultDecomposeLintRules")
	}
	if rule.Severity != config.DecomposeLintSeverityWarning {
		t.Fatalf("severity = %q, want warn", rule.Severity)
	}

	dir := t.TempDir()
	good := filepath.Join(dir, "verify.sh")
	if err := os.WriteFile(good, []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	noExec := filepath.Join(dir, "noexec.sh")
	if err := os.WriteFile(noExec, []byte("#!/bin/sh\n"), 0o644); err != nil {
		t.Fatal(err)
	}

	cases := []struct {
		name string
		task Task
		dir  string
		want int
	}{
		{"command string", Task{ID: "t", VerificationScript: "go test ./..."}, dir, 1},
		{"command string without dir", Task{ID: "t", VerificationScript: "go build && go test"}, "", 1},
		{"missing file", Task{ID: "t", VerificationScript: "nope.sh"}, dir, 1},
		{"not executable", Task{ID: "t", VerificationScript: "noexec.sh"}, dir, 1},
		{"runnable script", Task{ID: "t", VerificationScript: "verify.sh"}, dir, 0},
		{"missing but generated by the task", Task{ID: "t", VerificationScript: "new.sh", FilesGenerated: []string{"new.sh"}}, dir, 0},
		{"path without dir is unchecked", Task{ID: "t", VerificationScript: "nope.sh"}, "", 0},
		{"no script", Task{ID: "t"}, dir, 0},
	}
	for _, c := range cases {
		got := LintTasksIn(c.dir, []Story{mkDecomposeLintStory("s", c.task)}, []Rule{rule})
		if len(got) != c.want {
			t.Errorf("%s: %d findings, want %d: %+v", c.name, len(got), c.want, got)
			continue
		}
		if c.want == 1 && (got[0].Task != "t" || got[0].Severity != config.DecomposeLintSeverityWarning || got[0].Matched == "") {
			t.Errorf("%s: finding %+v, want a warn finding on task t with an excerpt", c.name, got[0])
		}
	}

	// The built-in template pack must not raise a block finding.
	story := testTaskTemplateStory(t)
	applied, _ := ApplyTaskTemplates([]Story{story}, "task templates", "p", testTaskTemplateCfg())
	for _, f := range LintTasksIn("", applied, DefaultDecomposeLintRules()) {
		if f.Severity == config.DecomposeLintSeverityBlock {
			t.Errorf("block finding on template task %s: rule %s", f.Task, f.RuleID)
		}
	}
}
